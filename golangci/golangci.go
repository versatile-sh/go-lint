// Package golangci generates a repository's .golangci.yml from the shared config and the repository overlay.
package golangci

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"

	"gopkg.in/yaml.v3"
)

//go:embed shared.yml
var shared []byte

//go:embed revive.toml
var revive []byte

// ConfigFile, FastConfigFile and ReviveFile are the generated full config, the lighter changed-tier config and the revive
// config; OverlayFile is the optional repository overlay. All are relative to the repository root.
const (
	ConfigFile     = ".golangci.yml"
	FastConfigFile = ".golangci-fast.yml"
	ReviveFile     = ".revive.toml"
	OverlayFile    = "lint/golangci.local.yml"
)

var heavy = []string{"gosec", "contextcheck", "sloglint", "testifylint"}

// ErrDrift is returned by Check when the committed config differs from the generated one.
var ErrDrift = errors.New("config out of date")

// Overlay is the only part a repository adds: extra exclusion and depguard rules, and an optional merge base
// so that golangci-lint reports only issues on lines changed since that ref.
type Overlay struct {
	Exclusions struct {
		Rules []yaml.Node `yaml:"rules"`
	} `yaml:"exclusions"`
	Depguard struct {
		Rules yaml.Node `yaml:"rules"`
	} `yaml:"depguard"`
	Issues struct {
		NewFromMergeBase string `yaml:"new-from-merge-base"`
	} `yaml:"issues"`
}

// Generate returns the shared config merged with the overlay, headed by a generated-file marker.
func Generate(overlay []byte) ([]byte, error) { return generate(overlay, false, OverlayFile) }

// GenerateFast returns the same config without the heavy linters, for the changed tier.
func GenerateFast(overlay []byte) ([]byte, error) { return generate(overlay, true, OverlayFile) }

func generate(overlay []byte, fast bool, overlayPath string) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(shared, &doc); err != nil {
		return nil, fmt.Errorf("shared config: %w", err)
	}
	root := doc.Content[0]
	if len(bytes.TrimSpace(overlay)) > 0 {
		var o Overlay
		dec := yaml.NewDecoder(bytes.NewReader(overlay))
		dec.KnownFields(true)
		if err := dec.Decode(&o); err != nil {
			return nil, fmt.Errorf("overlay %s: %w", overlayPath, err)
		}
		rules := lookup(root, "linters", "exclusions", "rules")
		for i := range o.Exclusions.Rules {
			rules.Content = append(rules.Content, &o.Exclusions.Rules[i])
		}
		if err := mergeDepguard(lookup(root, "linters", "settings", "depguard", "rules"), &o.Depguard.Rules); err != nil {
			return nil, err
		}
		if ref := o.Issues.NewFromMergeBase; ref != "" {
			issues := lookup(root, "issues")
			issues.Content = append(issues.Content,
				&yaml.Node{Kind: yaml.ScalarNode, Value: "new-from-merge-base"}, &yaml.Node{Kind: yaml.ScalarNode, Value: ref})
		}
	}
	if fast {
		dropLinters(root, heavy)
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Code generated by vlint golangci from github.com/versatile-sh/go-lint. DO NOT EDIT.\n# Add repository rules to %s and regenerate.\n", overlayPath)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, fmt.Errorf("encode config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("encode config: %w", err)
	}
	return buf.Bytes(), nil
}

type target struct {
	name string
	gen  func(overlay []byte, overlayPath string) ([]byte, error)
}

var targets = []target{
	{ConfigFile, func(o []byte, path string) ([]byte, error) { return generate(o, false, path) }},
	{FastConfigFile, func(o []byte, path string) ([]byte, error) { return generate(o, true, path) }},
	{ReviveFile, func([]byte, string) ([]byte, error) { return revive, nil }},
}

// OverlayName is the overlay file name inside an output directory chosen with WriteTo or CheckTo.
const OverlayName = "golangci.local.yml"

// Write generates the full config, the fast config and the revive config for the repository at dir.
func Write(dir string) error { return WriteTo(dir, "") }

// WriteTo is Write with the three files placed in out, relative to dir. The overlay is read from out when it holds one.
func WriteTo(dir, out string) error {
	overlay, path, err := readOverlay(dir, out)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dir, out), 0o750); err != nil {
		return fmt.Errorf("create %s: %w", out, err)
	}
	for _, t := range targets {
		body, err := t.gen(overlay, path)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, out, t.name), body, 0o644); err != nil { //nolint:gosec // a committed config file is world-readable
			return fmt.Errorf("write %s: %w", t.name, err)
		}
	}
	return nil
}

// Check returns ErrDrift when a generated file of the repository is missing or differs from what this version generates.
func Check(dir string) error { return CheckTo(dir, "") }

// CheckTo is Check for files placed in out, relative to dir.
func CheckTo(dir, out string) error {
	overlay, path, err := readOverlay(dir, out)
	if err != nil {
		return err
	}
	for _, t := range targets {
		want, err := t.gen(overlay, path)
		if err != nil {
			return err
		}
		got, err := os.ReadFile(filepath.Join(dir, out, t.name)) //nolint:gosec // reads the repository the caller named
		if err != nil || !bytes.Equal(got, want) {
			return fmt.Errorf("%s: %w: run vlint golangci", t.name, ErrDrift)
		}
	}
	return nil
}

func readOverlay(dir, out string) ([]byte, string, error) {
	if out != "" {
		path := filepath.ToSlash(filepath.Join(out, OverlayName))
		overlay, err := os.ReadFile(filepath.Join(dir, path)) //nolint:gosec // reads the repository the caller named
		if err == nil || !errors.Is(err, os.ErrNotExist) {
			return overlay, path, err
		}
	}
	overlay, err := os.ReadFile(filepath.Join(dir, OverlayFile)) //nolint:gosec // reads the repository the caller named
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, OverlayFile, fmt.Errorf("read %s: %w", OverlayFile, err)
	}
	return overlay, OverlayFile, nil
}

func dropLinters(root *yaml.Node, names []string) {
	linters := lookup(root, "linters")
	if enable := lookup(linters, "enable"); enable != nil {
		enable.Content = slices.DeleteFunc(enable.Content, func(n *yaml.Node) bool { return slices.Contains(names, n.Value) })
	}
	settings := lookup(linters, "settings")
	if settings != nil {
		for i := 0; i+1 < len(settings.Content); i += 2 {
			if slices.Contains(names, settings.Content[i].Value) {
				settings.Content = slices.Delete(settings.Content, i, i+2)
				i -= 2
			}
		}
	}
	if rules := lookup(linters, "exclusions", "rules"); rules != nil {
		for _, r := range rules.Content {
			if ls := lookup(r, "linters"); ls != nil {
				ls.Content = slices.DeleteFunc(ls.Content, func(n *yaml.Node) bool { return slices.Contains(names, n.Value) })
			}
		}
		rules.Content = slices.DeleteFunc(rules.Content, func(r *yaml.Node) bool {
			ls := lookup(r, "linters")
			return ls != nil && len(ls.Content) == 0
		})
	}
}

func mergeDepguard(base, add *yaml.Node) error {
	if add.Kind == 0 {
		return nil
	}
	if add.Kind != yaml.MappingNode {
		return fmt.Errorf("overlay depguard.rules must be a mapping")
	}
	for i := 0; i+1 < len(add.Content); i += 2 {
		if lookup(base, add.Content[i].Value) != nil {
			return fmt.Errorf("overlay depguard rule %q redefines a shared rule", add.Content[i].Value)
		}
		base.Content = append(base.Content, add.Content[i], add.Content[i+1])
	}
	return nil
}

func lookup(n *yaml.Node, keys ...string) *yaml.Node {
	for _, k := range keys {
		var next *yaml.Node
		for i := 0; n != nil && n.Kind == yaml.MappingNode && i+1 < len(n.Content); i += 2 {
			if n.Content[i].Value == k {
				next = n.Content[i+1]
			}
		}
		if next == nil {
			return nil
		}
		n = next
	}
	return n
}
