// Package golangci generates a repository's .golangci.yml from the shared config and the repository overlay.
package golangci

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

//go:embed shared.yml
var shared []byte

// ConfigFile and OverlayFile are the generated config and the optional repository overlay, relative to the repository root.
const (
	ConfigFile  = ".golangci.yml"
	OverlayFile = "lint/golangci.local.yml"
)

// ErrDrift is returned by Check when the committed config differs from the generated one.
var ErrDrift = errors.New("config out of date")

// Overlay is the only part a repository adds: extra exclusion and depguard rules, and an optional merge base
// so that golangci-lint reports only issues on lines changed since that ref.
type Overlay struct {
	Exclusions struct {
		Rules []yaml.Node `yaml:"rules"`
	} `yaml:"exclusions"`
	Depguard struct {
		Rules yaml.Node `yaml:"rules"`
	} `yaml:"depguard"`
	Issues struct {
		NewFromMergeBase string `yaml:"new-from-merge-base"`
	} `yaml:"issues"`
}

// Generate returns the shared config merged with the overlay, headed by a generated-file marker.
func Generate(overlay []byte) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(shared, &doc); err != nil {
		return nil, fmt.Errorf("shared config: %w", err)
	}
	root := doc.Content[0]
	if len(bytes.TrimSpace(overlay)) > 0 {
		var o Overlay
		dec := yaml.NewDecoder(bytes.NewReader(overlay))
		dec.KnownFields(true)
		if err := dec.Decode(&o); err != nil {
			return nil, fmt.Errorf("overlay %s: %w", OverlayFile, err)
		}
		rules := lookup(root, "linters", "exclusions", "rules")
		for i := range o.Exclusions.Rules {
			rules.Content = append(rules.Content, &o.Exclusions.Rules[i])
		}
		if err := mergeDepguard(lookup(root, "linters", "settings", "depguard", "rules"), &o.Depguard.Rules); err != nil {
			return nil, err
		}
		if ref := o.Issues.NewFromMergeBase; ref != "" {
			issues := lookup(root, "issues")
			issues.Content = append(issues.Content,
				&yaml.Node{Kind: yaml.ScalarNode, Value: "new-from-merge-base"}, &yaml.Node{Kind: yaml.ScalarNode, Value: ref})
		}
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Code generated by vlint golangci from github.com/versatile-sh/go-lint. DO NOT EDIT.\n# Add repository rules to %s and regenerate.\n", OverlayFile)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, fmt.Errorf("encode config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("encode config: %w", err)
	}
	return buf.Bytes(), nil
}

// Write generates the config for the repository at dir and writes it to its ConfigFile.
func Write(dir string) error {
	out, err := generateFor(dir)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, ConfigFile), out, 0o644); err != nil { //nolint:gosec // a committed config file is world-readable
		return fmt.Errorf("write %s: %w", ConfigFile, err)
	}
	return nil
}

// Check returns ErrDrift when the repository's ConfigFile is missing or differs from what this version generates.
func Check(dir string) error {
	want, err := generateFor(dir)
	if err != nil {
		return err
	}
	got, err := os.ReadFile(filepath.Join(dir, ConfigFile)) //nolint:gosec // reads the repository the caller named
	if err != nil || !bytes.Equal(got, want) {
		return fmt.Errorf("%s: %w: run vlint golangci", ConfigFile, ErrDrift)
	}
	return nil
}

func generateFor(dir string) ([]byte, error) {
	overlay, err := os.ReadFile(filepath.Join(dir, OverlayFile)) //nolint:gosec // reads the repository the caller named
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("read %s: %w", OverlayFile, err)
	}
	return Generate(overlay)
}

func mergeDepguard(base, add *yaml.Node) error {
	if add.Kind == 0 {
		return nil
	}
	if add.Kind != yaml.MappingNode {
		return fmt.Errorf("overlay depguard.rules must be a mapping")
	}
	for i := 0; i+1 < len(add.Content); i += 2 {
		if lookup(base, add.Content[i].Value) != nil {
			return fmt.Errorf("overlay depguard rule %q redefines a shared rule", add.Content[i].Value)
		}
		base.Content = append(base.Content, add.Content[i], add.Content[i+1])
	}
	return nil
}

func lookup(n *yaml.Node, keys ...string) *yaml.Node {
	for _, k := range keys {
		var next *yaml.Node
		for i := 0; n != nil && n.Kind == yaml.MappingNode && i+1 < len(n.Content); i += 2 {
			if n.Content[i].Value == k {
				next = n.Content[i+1]
			}
		}
		if next == nil {
			return nil
		}
		n = next
	}
	return n
}
